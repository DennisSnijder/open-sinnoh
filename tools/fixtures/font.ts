export const FONT_CHARS = [' ', ...Array.from({ length: 0x7f - 0x21 }, (_, i) => String.fromCharCode(0x21 + i)), 'é'];

export function buildFixtureFont(): { png: Uint8Array; chars: string; widths: number[]; cellWidth: number; cellHeight: number } {
  const rows = Math.ceil(FONT_CHARS.length / COLS);
  const W = COLS * CELL_W;
  const H = rows * CELL_H;
  const rgba = new Uint8Array(W * H * 4);
  const put = (x: number, y: number, c: number[]) => {
    const o = (y * W + x) * 4;
    if (c === SHADOW && rgba[o + 3]) return; // ink wins over shadow
    rgba.set(c, o);
  };
  const widths = FONT_CHARS.map((ch, i) => {
    if (ch === ' ') return 4;
    const shape = GLYPHS[ch];
    if (!shape) throw new Error(`fixture font: no glyph for "${ch}"`);
    const lines = shape.split('|');
    const w = Math.max(...lines.map((l) => l.length));
    if (w > CELL_W - 1 || lines.length > CELL_H - TOP - 1) throw new Error(`fixture font: "${ch}" does not fit the cell`);
    const ox = (i % COLS) * CELL_W;
    const oy = Math.floor(i / COLS) * CELL_H + TOP;
    for (const [color, d] of [
      [SHADOW, 1],
      [FG, 0],
    ] as const)
      lines.forEach((l, y) => [...l].forEach((p, x) => p === '#' && put(ox + x + d, oy + y + d, color)));
    return w + 1;
  });
  return { png: encodePng(W, H, rgba), chars: FONT_CHARS.join(''), widths, cellWidth: CELL_W, cellHeight: CELL_H };
}
